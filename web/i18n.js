(function initI18n() {
  function getPreferredLanguage() {
    const saved = localStorage.getItem('hk_pref_lang');
    if (saved && I18N_TRANSLATIONS[saved]) return saved;
    const browserLang = (navigator.language || navigator.userLanguage || 'en').slice(0, 2).toLowerCase();
    if (I18N_TRANSLATIONS[browserLang]) return browserLang;
    return 'en';
  }

  function applyLanguage(langCode) {
    const t = I18N_TRANSLATIONS[langCode] || I18N_TRANSLATIONS.en;
    document.documentElement.lang = langCode;
    document.documentElement.dir = t.dir || 'ltr';
    localStorage.setItem('hk_pref_lang', langCode);

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key]) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = t[key];
        } else {
          el.textContent = t[key];
        }
      }
    });

    const activeFlag = document.getElementById('currentLangFlag');
    const activeLabel = document.getElementById('currentLangLabel');
    if (activeFlag) activeFlag.textContent = t.flag;
    if (activeLabel) activeLabel.textContent = t.langName;

    document.querySelectorAll('.lang-option').forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === langCode);
    });
  }

  window.setLanguage = applyLanguage;
  window.getCurrentLanguage = getPreferredLanguage;

  document.addEventListener('DOMContentLoaded', () => {
    const initial = getPreferredLanguage();
    applyLanguage(initial);

    // Build or attach language selector
    const langPickerBtn = document.getElementById('langPickerBtn');
    const langDropdown = document.getElementById('langDropdown');
    if (langPickerBtn && langDropdown) {
      langDropdown.innerHTML = Object.entries(I18N_TRANSLATIONS).map(([code, item]) => `
        <button class="lang-option ${code === initial ? 'active' : ''}" data-lang="${code}" onclick="window.setLanguage('${code}'); document.getElementById('langDropdown').classList.add('hidden');">
          <span class="lang-flag">${item.flag}</span>
          <span class="lang-text">${item.langName}</span>
        </button>
      `).join('');

      langPickerBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        langDropdown.classList.toggle('hidden');
      });

      document.addEventListener('click', () => {
        langDropdown.classList.add('hidden');
      });
    }
  });
})();
